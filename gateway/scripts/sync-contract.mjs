// Writes src/contract.ts from the app's MCP tool contract, so the gateway and
// the phone list the same tools. Run after changing app/assets/mcp/tools.json:
//   npm run sync-contract
import { readFileSync, writeFileSync } from "node:fs";

const json = JSON.parse(readFileSync(new URL("../../app/assets/mcp/tools.json", import.meta.url), "utf8"));
const body = `// Generated by scripts/sync-contract.mjs from app/assets/mcp/tools.json. Do not edit.\n// SPDX-License-Identifier: AGPL-3.0-only\nexport const contract = ${JSON.stringify(json, null, 2)} as const;\n`;
writeFileSync(new URL("../src/contract.ts", import.meta.url), body);
