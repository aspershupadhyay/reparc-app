"""Turns the outlined RepArc wordmark (wordmark.svg, exported from Figma)
into Dart drawing calls in lib/core/brand_wordmark.dart.

    python3 -I tool/brand/svg_to_dart.py

The wordmark is Unbounded SemiBold (SIL Open Font License), outlined, so
the app draws it as shapes and does not ship the font. Handles the absolute
M, L, H, V, C, and Z commands that Figma writes.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(HERE))
SVG = os.path.join(HERE, "wordmark.svg")
OUT = os.path.join(APP, "lib", "core", "brand_wordmark.dart")


def ops(d):
    tokens = re.findall(r"[MLHVCZ]|-?\d*\.?\d+(?:e-?\d+)?", d)
    out, x, y, i, cmd = [], 0.0, 0.0, 0, None
    while i < len(tokens):
        t = tokens[i]
        if t in "MLHVCZ":
            cmd = t
            i += 1
            if cmd == "Z":
                out.append("..close()")
            continue
        n = lambda k: float(tokens[i + k])  # noqa: E731
        if cmd == "M":
            x, y = n(0), n(1)
            out.append(f"..moveTo({x:g}, {y:g})")
            i += 2
            cmd = "L"
        elif cmd == "L":
            x, y = n(0), n(1)
            out.append(f"..lineTo({x:g}, {y:g})")
            i += 2
        elif cmd == "H":
            x = n(0)
            out.append(f"..lineTo({x:g}, {y:g})")
            i += 1
        elif cmd == "V":
            y = n(0)
            out.append(f"..lineTo({x:g}, {y:g})")
            i += 1
        elif cmd == "C":
            a = [n(k) for k in range(6)]
            x, y = a[4], a[5]
            out.append("..cubicTo(" + ", ".join(f"{v:g}" for v in a) + ")")
            i += 6
        else:
            raise ValueError(cmd)
    return out


def main():
    svg = open(SVG).read()
    w, h = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).groups()
    lines = []
    for d in re.findall(r'd="([^"]+)"', svg):
        lines += ops(d)
    body = "\n".join("    " + line for line in lines)
    dart = f"""// Generated by tool/brand/svg_to_dart.py from tool/brand/wordmark.svg. Do not edit.
//
// The RepArc wordmark: Unbounded SemiBold (SIL Open Font License), kerned by
// hand at p-A and r-c, then outlined in Figma.
import 'dart:ui';

/// Size of the wordmark's box in its own units. Capitals are 75 units tall
/// from the top; the p descends to the bottom.
const wordmarkSize = Size({float(w):g}, {float(h):g});

/// Height of the capital letters, in wordmark units.
const wordmarkCapHeight = 75.0;

/// The wordmark outline in wordmark units (see [wordmarkSize]).
final Path wordmarkPath = Path()
{body};
"""
    open(OUT, "w").write(dart)
    print(f"{len(lines)} commands -> {OUT}")


if __name__ == "__main__":
    main()
